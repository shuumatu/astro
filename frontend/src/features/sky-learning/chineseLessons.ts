const hip = (...ids: number[]) => ids.map(id => `HIP:${id}`)
const figures = (...ids: number[]) => ids.map(id => `asterism-${String(id).padStart(3, '0')}`)
function course(id: string, stage: string, title: string, figureIds: number[], targets: number[], description: string, tip: string): LessonDefinition {
  return { id: `cn-${id}`, stage: `cn-${stage}`, title, asterismIds: figures(...figureIds), constellationIds: [], targetIds: hip(...targets), description, tip }
}

